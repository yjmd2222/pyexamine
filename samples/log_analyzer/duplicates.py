
def _template(entry, flag, tag, weight, source):
    result = []
    result.append(str(entry).strip())
    result.append(str(flag).strip())
    result.append(str(tag).strip())
    result.append(str(weight).strip())
    result.append(str(source).strip())
    result.append("ok")
    return ":".join(result)


def normalize_a(entry, flag, tag, weight, source):
    out = _template(entry, flag, tag, weight, source)
    out = out.replace("::", ":")
    out = out.strip()
    out = out + ""
    return out


